def classify(name: str) -> tuple[str, str] | None:
    """Classify a product name. Returns (major, middle) or None."""
    name_lower = name.lower()
    for major, middle, keywords in RULES:
        for kw in keywords:
            if kw.lower() in name_lower:
                return (major, middle)
    return None


def main():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    cur.execute("SELECT id, name FROM products WHERE category_middle = '미분류'")
    products = cur.fetchall()
    print(f"미분류 products: {len(products)}")

    classified = 0
    still_unmatched = []

    for p in products:
        result = classify(p["name"])
        if result:
            major, middle = result
            cur.execute(
                "UPDATE products SET category_major = ?, category_middle = ? WHERE id = ?",
                (major, middle, p["id"]),
            )
            classified += 1
        else:
            still_unmatched.append(p)

    conn.commit()
    conn.close()

    print(f"Classified: {classified}")
    print(f"Still unmatched: {len(still_unmatched)}")

    if still_unmatched:
        print("\nRemaining unmatched:")
        for p in still_unmatched:
            print(f"  [{p['id']:4d}] {p['name']}")


if __name__ == "__main__":
    main()
